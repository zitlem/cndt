export type PageId = keyof typeof page;

const MARKER = /\[\[([A-Za-z0-9.-]+)\]\]/g;

function fill(value: string): string {
  return value.replace(MARKER, (marker, id: string) => (id in page ? page[id as PageId] : marker));
}

/** Replaces every `[[id]]` marker in the page with its text. Run once, first. */
export function fillPage(root: Document): void {
  const attributes = ["title", "aria-label", "placeholder"];
  const walker = root.createTreeWalker(root.documentElement, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  for (let node = walker.currentNode; node; node = walker.nextNode() as Node) {
    if (node.nodeType === Node.TEXT_NODE) {
      const text = node.nodeValue ?? "";
      if (text.includes("[[")) node.nodeValue = fill(text);
    } else if (node instanceof Element) {
      for (const name of attributes) {
        const value = node.getAttribute(name);
        if (value?.includes("[[")) node.setAttribute(name, fill(value));
      }
    }
  }
}

