export type PageId = keyof typeof page;

const MARKER = /\[\[([A-Za-z0-9.-]+)\]\]/g;

/** Ids a marker named that the table does not have; each is logged once. */
const missing = new Set<string>();

function fill(value: string): string {
  return value.replace(MARKER, (marker, id: string) => {
    if (Object.hasOwn(page, id)) return page[id as PageId];
    // Loud, and visible on screen: the marker stays, so the key's name shows.
    if (!missing.has(id)) {
      missing.add(id);
      console.error(`strings: index.html asks for "${id}", which strings.ts does not have`);
    }
    return marker;
  });
}

/**
 * Replaces every `[[id]]` marker in the page with its text. Runs first (see
 * boot.ts). A node that cannot be filled is logged and skipped, so one
 * failure never leaves the rest of the page in markers.
 */
export function fillPage(root: Document): void {
  const attributes = ["title", "aria-label", "placeholder"];
  const walker = root.createTreeWalker(root.documentElement, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  for (let node: Node | null = walker.currentNode; node; node = walker.nextNode()) {
    try {
      if (node.nodeType === Node.TEXT_NODE) {
        const text = node.nodeValue ?? "";
        if (text.includes("[[")) node.nodeValue = fill(text);
      } else if (node instanceof Element) {
        for (const name of attributes) {
          const value = node.getAttribute(name);
          if (value?.includes("[[")) node.setAttribute(name, fill(value));
        }
      }
    } catch (error) {
      console.error("strings: could not fill a node of the page", error);
    }
  }
}

